(()=>{
  // The authoritative translator is a local .NET runtime built by GitHub Actions.
  // It is deliberately restricted to canonical examples: we never execute arbitrary editor C#.
  const supported=new Set(['outgoing','incoming','chained','filter']);
  const normalize=query=>query.replace(/\s+/g,' ').trim();

  async function load(){
    const button=document.getElementById('enable-real-gorm');
    if(button){button.disabled=true;button.textContent='Loading .NET runtime…';}
    try{
      const {dotnet}=await import('./playground-wasm/_framework/dotnet.js');
      const runtime=await dotnet.create();
      const exports=await runtime.getAssemblyExports(runtime.getConfig().mainAssemblyName);
      const explain=exports.Gorm?.Playground?.Browser?.Program?.ExplainPreset;
      const explainIntent=exports.Gorm?.Playground?.Browser?.Program?.ExplainIntent;
      const explainTraversal=exports.Gorm?.Playground?.Browser?.Program?.ExplainTraversal;
      const getTraversalCatalog=exports.Gorm?.Playground?.Browser?.Program?.TraversalCatalog;
      const explainPath=exports.Gorm?.Playground?.Browser?.Program?.ExplainPath;
      const getPathCatalog=exports.Gorm?.Playground?.Browser?.Program?.PathCatalog;
      const explainPredicate=exports.Gorm?.Playground?.Browser?.Program?.ExplainPredicate;
      const getPredicateCatalog=exports.Gorm?.Playground?.Browser?.Program?.PredicateCatalog;
      const explainCombined=exports.Gorm?.Playground?.Browser?.Program?.ExplainCombinedPredicate;
      if(typeof explain!=='function'||typeof explainIntent!=='function'
        ||typeof explainTraversal!=='function'||typeof getTraversalCatalog!=='function'
        ||typeof explainPath!=='function'||typeof getPathCatalog!=='function'
        ||typeof explainPredicate!=='function'||typeof getPredicateCatalog!=='function'
        ||typeof explainCombined!=='function')
        throw new Error('Required GORM Explain/traversal/path exports are missing');
      const traversalCatalog=JSON.parse(getTraversalCatalog());
      const pathCatalog=JSON.parse(getPathCatalog());
      const predicateCatalog=JSON.parse(getPredicateCatalog());
      if(!Array.isArray(traversalCatalog)||!traversalCatalog.length)throw new Error('GORM model returned no traversable graph routes');
      if(!Array.isArray(pathCatalog)||!pathCatalog.length)throw new Error('GORM model returned no mapped two-hop paths');
      if(!Array.isArray(predicateCatalog)||!predicateCatalog.length)throw new Error('GORM model returned no mapped predicates');
      await runtime.runMain();

      window.GormPlaygroundEngine={
        traversalCatalog,
        pathCatalog,
        predicateCatalog,
        metadata:{
          id:'gorm-wasm-hybrid',
          label:'GORM Explain() + preview',
          version:'net10.0 source',
          kind:'hybrid',
          authoritative:false,
          execution:'client-side .NET WebAssembly'
        },
        translate(query){
          const preview=window.GormPreviewEngine.translate(query);
          const example=(window.GormPlaygroundExamples??[]).find(item=>supported.has(item.key)&&normalize(item.query)===normalize(query));
          if(!example){
            const combined=window.GormPlaygroundCombined?.parse(query);
            if(combined){
              const explained=JSON.parse(explainCombined(JSON.stringify(combined)));
              if(typeof explained.sql!=='string'||!Array.isArray(explained.parameters))throw new Error('GORM combined Explain contract failed.');
              return {
                ...preview,
                model:{...preview.model, predicate:null, combinedPredicates:[
                  {column:'Name',value:combined.name},{column:'State',value:combined.state}
                ]},
                ok:true,
                sql:explained.sql,
                parameters:explained.parameters,
                authoritative:true,
                notes:['Generated by the real GORM SQL provider for validated Name AND State equality predicates.',
                  'Both parameters are bound by GORM. Arbitrary C# is not evaluated.']
              };
            }
            const mappedPredicate=window.GormPlaygroundPredicates?.parse(query);
            if(mappedPredicate){
              const explained=JSON.parse(explainPredicate(JSON.stringify(mappedPredicate)));
              if(typeof explained.sql!=='string'||!Array.isArray(explained.parameters))throw new Error('GORM mapped predicate Explain contract failed.');
              return {
                ...preview,
                ok:true,
                sql:explained.sql,
                parameters:explained.parameters,
                authoritative:true,
                notes:['Generated by real GORM Explain() using an equality predicate validated against mapped model properties.',
                  'Bound parameters come directly from the GORM SQL provider, not from JavaScript.']
              };
            }
            const path=window.GormPlaygroundPaths?.parse(query);
            if(path){
              const explained=JSON.parse(explainPath(JSON.stringify(path)));
              if(typeof explained.sql!=='string'||!Array.isArray(explained.parameters))throw new Error('GORM two-hop Explain contract failed.');
              return {
                ...preview,
                ok:true,
                sql:explained.sql,
                parameters:explained.parameters,
                authoritative:true,
                notes:['Compiled using the real GORM path LINQ provider, with both hop mappings validated by .NET.',
                  'Provider SQL and bound parameters are authoritative; editor C# is never executed.']
              };
            }
            const traversal=window.GormPlaygroundTraversals?.parse(query);
            if(traversal){
              const explained=JSON.parse(explainTraversal(JSON.stringify(traversal)));
              if(typeof explained.sql!=='string'||!Array.isArray(explained.parameters))throw new Error('GORM traversal contract failed.');
              return {
                ...preview,
                ok:true,
                sql:explained.sql,
                parameters:explained.parameters,
                authoritative:true,
                notes:['Translated by real GORM Explain() with a route verified against the .NET graph model.',
                  'Incoming/outgoing direction and node GUID are validated independently in WebAssembly.']
              };
            }
            // Strictly parse the bounded LINQ shape, then validate AGAIN inside the .NET provider.
            // Non-matching C# is NEVER passed to the runtime or labelled as authoritative.
            const intent=window.GormPlaygroundEditable?.parse(query);
            if(intent){
              const explained=JSON.parse(explainIntent(JSON.stringify(intent)));
              if(typeof explained.sql!=='string'||!Array.isArray(explained.parameters))throw new Error('GORM ExplainIntent contract failed.');
              return {
                ...preview,
                ok:true,
                sql:explained.sql,
                parameters:explained.parameters,
                authoritative:true,
                notes:['Generated by the real GORM LINQ provider using validated editable v1 intent (no C# eval or database).',
                  'SQL parameters come directly from GORM Explain(), not the JavaScript preview.']
              };
            }
            return {
              ...preview,
              authoritative:false,
              notes:['Illustrative JavaScript preview: this editor text does not match a supported verified GORM query intent.',...(preview.notes??[])]
            };
          }
          // Fail closed: if the actual .NET translator throws, do not silently substitute JavaScript SQL.
          const sql=explain(example.key);
          return {
            ...preview,
            ok:true,
            sql,
            authoritative:true,
            notes:['Generated by GORM Explain() running locally in .NET 10 WebAssembly (no database or server).',
              'The preset uses fixed demonstration parameter values; editable filters require the strict v1 schema.']
          };
        }
      };
      if(button)button.textContent='Real GORM enabled';
      document.dispatchEvent(new CustomEvent('gorm:runtime-ready'));
    }catch(error){
      // GitHub Pages may not have a WASM bundle during local documentation development.
      // The existing clearly-labelled, non-authoritative preview remains usable.
      if(button){button.disabled=false;button.textContent='Retry real GORM SQL';}
      console.warn('GORM WebAssembly runtime unavailable; using documentation preview.',error);
    }
  }
  document.getElementById('enable-real-gorm')?.addEventListener('click',()=>void load());
})();
