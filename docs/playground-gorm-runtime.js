(()=>{
  // The authoritative translator is a local .NET runtime built by GitHub Actions.
  // It is deliberately restricted to canonical examples: we never execute arbitrary editor C#.
  const supported=new Set(['outgoing','incoming','chained','filter']);
  const normalize=query=>query.replace(/\s+/g,' ').trim();

  async function load(){
    try{
      const {dotnet}=await import('./playground-wasm/_framework/dotnet.js');
      const runtime=await dotnet.create();
      const exports=await runtime.getAssemblyExports(runtime.getConfig().mainAssemblyName);
      const explain=exports.Gorm?.Playground?.Browser?.Program?.ExplainPreset;
      if(typeof explain!=='function')throw new Error('GORM ExplainPreset export is missing');
      await runtime.runMain();

      window.GormPlaygroundEngine={
        metadata:{
          id:'gorm-wasm-hybrid',
          label:'GORM Explain() + preview',
          version:'net10.0 source',
          kind:'hybrid',
          authoritative:false,
          execution:'client-side .NET WebAssembly'
        },
        translate(query){
          const preview=window.GormPreviewEngine.translate(query);
          const example=(window.GormPlaygroundExamples??[]).find(item=>supported.has(item.key)&&normalize(item.query)===normalize(query));
          if(!example)return {
            ...preview,
            authoritative:false,
            notes:['Illustrative JavaScript preview: only the four original traversal/filter presets have verified real GORM SQL.',...(preview.notes??[])]
          };
          // Fail closed: if the actual .NET translator throws, do not silently substitute JavaScript SQL.
          const sql=explain(example.key);
          return {
            ...preview,
            ok:true,
            sql,
            authoritative:true,
            notes:['Generated by GORM Explain() running locally in .NET 10 WebAssembly (no database or server).',
              'The preset uses fixed demonstration parameter values; parameters are not supplied from arbitrary C#.']
          };
        }
      };
      document.dispatchEvent(new CustomEvent('gorm:runtime-ready'));
    }catch(error){
      // GitHub Pages may not have a WASM bundle during local documentation development.
      // The existing clearly-labelled, non-authoritative preview remains usable.
      console.warn('GORM WebAssembly runtime unavailable; using documentation preview.',error);
    }
  }
  void load();
})();
